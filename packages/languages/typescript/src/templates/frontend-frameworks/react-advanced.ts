export function reactAdvancedTemplate(): string {
  return [
    "import React, { Suspense, useMemo } from 'react';",
    "",
    "type Props = { id: string };",
    "",
    "const resource = { read: () => ({ name: 'demo' }) };",
    "",
    "function Details({ id }: Props) {",
    "  const data = resource.read();",
    "  const computed = useMemo(() => `${data.name}-${id}`, [data, id]);",
    "  return <div>{computed}</div>;",
    "}",
    "",
    "class ErrorBoundary extends React.Component<",
    "  { children: React.ReactNode },",
    "  { hasError: boolean }",
    "> {",
    "  state = { hasError: false };",
    "  static getDerivedStateFromError() { return { hasError: true }; }",
    "  render() {",
    "    return this.state.hasError ? <div>Failed</div> : this.props.children;",
    "  }",
    "}",
    "",
    "export function Page(props: Props) {",
    "  return (",
    "    <ErrorBoundary>",
    "      <Suspense fallback={<div>Loading...</div>}>",
    "        <Details {...props} />",
    "      </Suspense>",
    "    </ErrorBoundary>",
    "  );",
    "}",
  ].join("\n");
}
